        alpha = float(params.get("alpha", 0.05))

        # Expect canonical: gene_id + numeric sample columns
        if "gene_id" not in df.columns:
            raise ValueError("DE expects a canonical matrix with 'gene_id' + sample columns.")

        expr = df.set_index("gene_id").select_dtypes(include=np.number)  # genes x samples

        # Look for sample metadata in dataset folder
        ds_dir = Path(p).parent
        meta = None
        for cand in ["sample_meta.csv", "sample_metadata.csv", "metadata.csv"]:
            mp = ds_dir / cand
            if mp.exists():
                meta = pd.read_csv(mp)
                break

        if meta is None or "sample_id" not in meta.columns or group_col not in meta.columns:
            raise ValueError(
                f"Sample metadata not found. Put a CSV in {ds_dir} "
                f"with columns sample_id,{group_col} (e.g., sample_meta.csv)."
            )

        meta = meta.dropna(subset=["sample_id", group_col])
        meta[group_col] = meta[group_col].astype(str)

        # Keep only samples present in expression matrix
        meta = meta[meta["sample_id"].isin(expr.columns)]
        groups = sorted(meta[group_col].unique())
        if len(groups) != 2:
            raise ValueError(f"DE requires exactly 2 groups in '{group_col}', found: {groups}")

        g1, g2 = groups
        s1 = meta.loc[meta[group_col] == g1, "sample_id"].tolist()
        s2 = meta.loc[meta[group_col] == g2, "sample_id"].tolist()
        if len(s1) < 2 or len(s2) < 2:
            raise ValueError("Need at least 2 samples per group for a t-test.")

        # Welch t-test per gene
        rows = []
        for gene, row in expr.iterrows():
            a = row[s1].dropna().to_numpy(float)
            b = row[s2].dropna().to_numpy(float)
            if a.size < 2 or b.size < 2:
                pval = np.nan
                l2fc = np.nan
            else:
                t, pval = stats.ttest_ind(a, b, equal_var=False)
                # log2 fold change (group1 - group2)
                l2fc = float(np.log2(np.mean(a) + 1e-9) - np.log2(np.mean(b) + 1e-9))
            rows.append((gene, l2fc, pval))

        out = pd.DataFrame(rows, columns=["gene_id", "log2FC", "pval"]).dropna(subset=["pval"])
        out["fdr"] = _bh_fdr(out["pval"].values)
        out = out.sort_values("fdr")
        out.to_csv(outdir / "de.csv", index=False)

        # Volcano plot
        plt.figure()
        plt.scatter(out["log2FC"], -np.log10(out["pval"].clip(lower=1e-300)), s=6)
        plt.axhline(-np.log10(alpha), linestyle="--")
        plt.xlabel("log2 fold change"); plt.ylabel("-log10 p-value")
        plt.title(f"Differential Expression: {g1} vs {g2}")
        plt.tight_layout()
        plt.savefig(outdir / "de_volcano.png"); plt.close()

        arts = {
            "csv_url": _u(f"/files/runs/{run.id}/de.csv"),
            "pngs":   [_u(f"/files/runs/{run.id}/de_volcano.png")],
        }


