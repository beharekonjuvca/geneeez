def _autogroup_meta(df: pd.DataFrame, group_col: str, ds) -> pd.DataFrame:
    """
    Make a fake metadata with two groups:
    1) Try to infer groups from sample names by keywords.
    2) Fallback to k-means (k=2) on samples in expression space.
    Writes sample_meta_autogenerated.csv in the dataset folder and returns it.
    """
    ds_dir = _dataset_dir(ds)
    num = df.select_dtypes(include=np.number).copy()
    cols = list(num.columns)
    if len(cols) < 4:
        raise ValueError("Need ≥4 samples to auto-group.")

    # 1) Try name keywords
    names = pd.Series(cols, dtype=str).str.lower()
    a_kw = names.str.contains(r"(control|ctrl|wt|normal)")
    b_kw = names.str.contains(r"(treated|case|mut|tumor|ko|kd)")

    if a_kw.any() and b_kw.any():
        grp = np.where(a_kw, "A", np.where(b_kw, "B", None))
        meta = pd.DataFrame({"sample_id": cols, group_col: grp}).dropna()
        if meta[group_col].nunique() == 2:
            outp = ds_dir / "sample_meta_autogenerated.csv"
            meta.to_csv(outp, index=False)
            return meta

    # 2) Fallback: k-means on PCA of samples
    from sklearn.preprocessing import StandardScaler
    from sklearn.decomposition import PCA
    from sklearn.cluster import KMeans

    X = StandardScaler().fit_transform(num.T.values)             # samples × genes
    n_pc = max(2, min(10, X.shape[1] - 1))
    PCs = PCA(n_components=n_pc, random_state=0).fit_transform(X)
    km = KMeans(n_clusters=2, n_init=10, random_state=0).fit(PCs)

    labels = np.where(km.labels_ == 0, "A", "B")
    meta = pd.DataFrame({"sample_id": cols, group_col: labels})
    outp = ds_dir / "sample_meta_autogenerated.csv"
    meta.to_csv(outp, index=False)
    return meta


def _read_sample_meta(ds, group_col: str = "group") -> pd.DataFrame:
    ds_dir = _dataset_dir(ds)
    candidates = ["sample_meta.csv", "sample_metadata.csv", "metadata.csv"]
    for name in candidates:
        fp = ds_dir / name
        if fp.exists():
            meta = pd.read_csv(fp)
            cols = {c.lower(): c for c in meta.columns}
            if "sample_id" not in cols or group_col.lower() not in cols:
                raise ValueError(
                    f"Metadata {fp.name} must have columns: sample_id,{group_col}"
                )
            meta = meta[[cols["sample_id"], cols[group_col.lower()]]].copy()
            meta.columns = ["sample_id", group_col]
            meta["sample_id"] = meta["sample_id"].astype(str)
            meta[group_col] = meta[group_col].astype(str)
            return meta

    # Create a template to help the user
    expr = pd.read_parquet(_dataset_dir(ds) / "matrix.parquet") \
        if (_dataset_dir(ds) / "matrix.parquet").exists() \
        else pd.read_csv(_dataset_dir(ds) / "matrix.csv")
    expr_cols = [c for c in expr.columns if c.lower() != "gene_id"]
    template = pd.DataFrame({"sample_id": expr_cols, group_col: ""})
    tmpl_path = _dataset_dir(ds) / "sample_meta_template.csv"
    template.to_csv(tmpl_path, index=False)

    raise FileNotFoundError(
        f"Sample metadata not found. I wrote a template at {tmpl_path}. "
        f"Fill '{group_col}' for exactly two groups (≥2 samples each) and rerun."
    )

def _bh_fdr(pvals: np.ndarray) -> np.ndarray:
    """Benjamini–Hochberg FDR."""
    m = len(pvals)
    order = np.argsort(pvals)
    ranked = pvals[order]
    fdr = ranked * m / (np.arange(m) + 1)
    fdr = np.minimum.accumulate(fdr[::-1])[::-1]
    out = np.empty_like(fdr)
    out[order] = fdr
    return np.clip(out, 0, 1)

def _log(msg, *args):
    print("[analytics]", msg.format(*args))

def _slug(s: str) -> str:
    try:
        return re.sub(r"[^a-z0-9]+", "-", (s or "").lower()).strip("-")
    except Exception:
        return ""

def _pick_best(files: list[Path]) -> Path:
    pref = {".parquet":0, ".pq":0, ".csv":1, ".tsv":2, ".txt":3, ".xlsx":4, ".xls":4}
    files.sort(key=lambda p: (pref.get(p.suffix.lower(), 99), -p.stat().st_size))
    return files[0]

def _dataset_path(ds: Dataset) -> Path:
    """
    Find the dataset file under uploads/<owner_id>/... (your layout),
    with helpful logs at every step. Falls back to a sensible single file
    if no exact match by id/title is found.
    """
    _log("cwd: {}", Path(os.getcwd()).resolve())
    _log("UPLOAD_ROOT: {}", UPLOAD_ROOT)
    _log("dataset id={}, owner_id={}, title={!r}", ds.id, getattr(ds, "owner_id", None), getattr(ds, "title", None))

    for attr in ("file_path", "path", "storage_uri", "local_path"):
        v = getattr(ds, attr, None)
        _log("check attr {} -> {}", attr, v)
        if v:
            p = Path(v)
            _log("  exists={} resolved={}", p.exists(), p.resolve())
            if p.exists():
                _log("using direct path: {}", p)
                return p

    owner_id = str(getattr(ds, "owner_id", "") or "")
    user_dir = (UPLOAD_ROOT / owner_id)
    _log("user_dir {}", user_dir)

    if not user_dir.exists():
        try:
            sample = [str(p) for p in list(UPLOAD_ROOT.iterdir())[:20]]
        except FileNotFoundError:
            sample = ["<uploads dir missing>"]
        _log("user_dir missing. top-level under uploads: {}", sample)
        raise ValueError("Dataset file path not found (user dir missing)")

    def collect(base: Path, limit=5000) -> list[Path]:
        files = []
        for i, p in enumerate(base.rglob("*")):
            if i > limit:
                _log("scan limit {} reached under {}", limit, base)
                break
            try:
                if p.is_file() and p.suffix.lower() in ALLOWED_EXTS:
                    files.append(p)
            except Exception:
                pass
        return files

    id_pat = str(ds.id)
    by_id = [p for p in collect(user_dir) if id_pat in str(p)]
    _log("matches containing dataset id '{}': {}", id_pat, len(by_id))
    if by_id:
        pick = _pick_best(by_id)
        _log("picked by id: {}", pick)
        return pick

    title = getattr(ds, "title", None)
    if title:
        tslug = _slug(title)
        by_title = [p for p in collect(user_dir) if tslug and tslug in str(p).lower()]
        _log("matches containing title slug '{}': {}", tslug, len(by_title))
        if by_title:
            pick = _pick_best(by_title)
            _log("picked by title: {}", pick)
            return pick

    all_files = collect(user_dir)
    _log("fallback candidates under user dir: {}", len(all_files))
    if all_files:
        pick = _pick_best(all_files)
        _log("picked fallback: {}", pick)
        return pick

    _log("_dataset_path FAILED for dataset {} (owner {})", ds.id, owner_id)
    raise ValueError("Dataset file path not found")

def _load_df(p: Path) -> pd.DataFrame:
    compression = "infer" if p.suffix.lower() == ".gz" or str(p).endswith(".txt.gz") else None
    name = p.name
    if name.endswith(".txt.gz"):
        ext = ".txt"
    elif name.endswith(".tsv.gz"):
        ext = ".tsv"
    elif name.endswith(".csv.gz"):
        ext = ".csv"
    else:
        ext = p.suffix.lower()

    if ext in (".txt", ".tsv"):
        return pd.read_csv(
            p, sep="\t", comment="!", compression=compression, engine="python"
        )

    if ext in (".csv",):
        return pd.read_csv(p, compression=compression)

    if ext in (".parquet", ".pq"):
        return pd.read_parquet(p)

    if ext in (".xlsx", ".xls"):
        return pd.read_excel(p)

    return pd.read_csv(p, compression=compression)


